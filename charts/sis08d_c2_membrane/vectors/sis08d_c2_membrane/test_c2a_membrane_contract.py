def test_c2a_layout_matches_sos09b_address_policy():
    """Layout invariant: SOS-09-B address-offset policy lays each 32-bit
    channel at a 4-byte cursor starting from the SVD baseAddress.

    The chart has five 32-bit channels; cursor must advance 4, 4, 4, 4.
    """
    layout = _load_layout()
    names = [
        "membrane_command",
        "membrane_status",
        "transfer_mailbox_data",
        "transfer_mailbox_notify",
        "sram_window",
    ]
    assert set(layout.keys()) == set(names), (
        f"chart channel set drifted from C2-A contract: {sorted(layout.keys())}"
    )
    base = layout["membrane_command"]["address"]
    for i, name in enumerate(names):
        expected = base + 4 * i
        actual = layout[name]["address"]
        assert actual == expected, (
            f"layout drift on {name!r}: SOS-09-B policy expects "
            f"0x{expected:08X}, plans.json says 0x{actual:08X}"
        )


def test_c2a_ownership_sram_window_is_shared_mutex_locked():
    """Ownership invariant: SRAM window is SOS-owned (kind=shared) and
    serialised under a named mutex. The membrane contract requires the
    software side to NOT embed the SOS descriptor into the graph node.
    """
    layout = _load_layout()
    sram = layout["sram_window"]
    assert sram["channel_kind"] == "shared", (
        f"sram_window must be kind=shared (SOS-owned region); got "
        f"{sram['channel_kind']!r}"
    )
    assert sram["mutex"] == "sram_window_lock", (
        "sram_window must be guarded by sram_window_lock per chart "
        "annotation; mutex value drifted"
    )
    # Mailbox data carries the queue discipline, not shared semantics.
    assert layout["transfer_mailbox_data"]["channel_kind"] == "queue", (
        "transfer_mailbox_data must be kind=queue per SIS-08D §4"
    )


def test_c2a_command_status_round_trip_lifecycle():
    """Lifecycle invariant: command-write → status-publish round trip.

    Software issues Start; the membrane publishes Busy, then Ready;
    software reads the status, issues Stop, returns to Idle.

    The Python CPU stub emulates the membrane by having the test
    drive both sides — that's faithful to SIS-08D §5 step 1
    (interpreted simulation, no compiled backend required).
    """
    layout = _load_layout()
    cmd_addr = layout["membrane_command"]["address"]
    status_addr = layout["membrane_status"]["address"]

    h = PythonCpuStubHarness()
    h.register_channel(address=cmd_addr, width_bits=32)
    # Status: clear-on-read on the error_code byte per chart annotation.
    h.register_channel(
        address=status_addr,
        width_bits=32,
        clear_on_read_mask=ERROR_CODE_MASK,
        initial_value=(STATE_IDLE << STATE_FIELD_LSB),
    )

    # Software-side: write Start with seq=1.
    cmd_word = (CMD_START << CMD_FIELD_LSB) | (1 << SEQ_FIELD_LSB)
    h.bus.write(cmd_addr, cmd_word)

    # Membrane (hardware-side stub): publish Busy.
    h._registers[status_addr].value = (STATE_BUSY << STATE_FIELD_LSB) | BUSY_BIT
    observed = h.bus.read(status_addr)
    assert (observed & STATE_FIELD_MASK) == STATE_BUSY, (
        f"expected Busy state after Start; got 0x{observed:08X}"
    )
    assert observed & BUSY_BIT, "busy bit must be set while in Busy state"

    # Membrane: publish Ready.
    h._registers[status_addr].value = STATE_READY << STATE_FIELD_LSB
    observed = h.bus.read(status_addr)
    assert (observed & STATE_FIELD_MASK) == STATE_READY, (
        f"expected Ready state after work; got 0x{observed:08X}"
    )

    # Software: issue Stop.
    h.bus.write(cmd_addr, (CMD_STOP << CMD_FIELD_LSB) | (2 << SEQ_FIELD_LSB))
    h._registers[status_addr].value = STATE_IDLE << STATE_FIELD_LSB
    observed = h.bus.read(status_addr)
    assert (observed & STATE_FIELD_MASK) == STATE_IDLE, (
        f"expected return to Idle after Stop; got 0x{observed:08X}"
    )


def test_c2a_mailbox_single_slot_post_drain_cycle():
    """Transfer-surface invariant: single-slot mailbox post / drain
    with notify-side clear-on-read on non_empty.

    Per SIS-08D §4 + SIS-03 §4.10, the v1 transfer surface is a
    mailbox (one in-flight transfer at a time). The notify channel's
    non_empty bit strobes high on post and clears on the software
    side's read of the notify register.
    """
    layout = _load_layout()
    data_addr = layout["transfer_mailbox_data"]["address"]
    notify_addr = layout["transfer_mailbox_notify"]["address"]

    h = PythonCpuStubHarness()
    h.register_channel(address=data_addr, width_bits=32)
    h.register_channel(
        address=notify_addr,
        width_bits=32,
        clear_on_read_mask=NOTIFY_NON_EMPTY_BIT,
    )

    # Mailbox is initially empty.
    assert h.bus.read(notify_addr) & NOTIFY_NON_EMPTY_BIT == 0, (
        "notify.non_empty should reset clear"
    )

    # Hardware-side post: a transfer descriptor lands in the data
    # surface, the notify register reflects it (non_empty=1, priority=5).
    PAYLOAD = 0xDEADBEEF
    h._registers[data_addr].value = PAYLOAD
    h._registers[notify_addr].value = NOTIFY_NON_EMPTY_BIT | (5 << NOTIFY_PRIORITY_LSB)

    # Software-side observes the notification.
    notify_word = h.bus.read(notify_addr)
    assert notify_word & NOTIFY_NON_EMPTY_BIT, "non_empty must be set on post"
    assert (notify_word & NOTIFY_PRIORITY_MASK) >> NOTIFY_PRIORITY_LSB == 5, (
        "priority byte must round-trip across the notify surface"
    )

    # Read clears the non_empty latch (chart annotation: clear-on-read).
    next_word = h.bus.read(notify_addr)
    assert next_word & NOTIFY_NON_EMPTY_BIT == 0, (
        "non_empty must clear on read per chart side_effect annotation"
    )

    # Software-side drain: read the data surface.
    drained = h.bus.read(data_addr)
    assert drained == PAYLOAD, (
        f"mailbox drain must return the posted payload; got 0x{drained:08X}"
    )

    # Single-slot discipline: posting a second transfer while the slot
    # is still nominally "drained but not re-armed" is permitted — the
    # contract is one in-flight at the notify-level, not one ever-posted.
    # This test exercises the round-trip; multi-slot discipline is
    # out of scope per SIS-08D §4 ("Use a single-slot mailbox … for v1").


def test_c2a_command_while_busy_returns_error_status():
    """Failure-mode invariant: command-write while busy publishes
    state=Error with a non-zero error_code. The error_code latch
    clears on read per the chart's clear-on-read annotation.
    """
    layout = _load_layout()
    cmd_addr = layout["membrane_command"]["address"]
    status_addr = layout["membrane_status"]["address"]

    h = PythonCpuStubHarness()
    h.register_channel(address=cmd_addr, width_bits=32)
    h.register_channel(
        address=status_addr,
        width_bits=32,
        clear_on_read_mask=ERROR_CODE_MASK,
        # Start in Busy state — the hardware-side stub publishes Busy.
        initial_value=(STATE_BUSY << STATE_FIELD_LSB) | BUSY_BIT,
    )

    # Software-side: try to issue a fresh Start while the membrane is busy.
    h.bus.write(cmd_addr, (CMD_START << CMD_FIELD_LSB) | (3 << SEQ_FIELD_LSB))

    # Membrane reaction: latch Error state with ERR_BUSY_WRITE_REJECTED.
    h._registers[status_addr].value = (
        (STATE_ERROR << STATE_FIELD_LSB)
        | (ERR_BUSY_WRITE_REJECTED << ERROR_CODE_LSB)
    )

    observed = h.bus.read(status_addr)
    assert (observed & STATE_FIELD_MASK) == STATE_ERROR, (
        f"expected Error state after busy-write; got 0x{observed:08X}"
    )
    assert (
        (observed & ERROR_CODE_MASK) >> ERROR_CODE_LSB
    ) == ERR_BUSY_WRITE_REJECTED, (
        "error_code byte must carry the rejected-while-busy code"
    )

    # Clear-on-read: a follow-up read must show error_code=0.
    follow_up = h.bus.read(status_addr)
    assert (follow_up & ERROR_CODE_MASK) == 0, (
        "error_code must clear on read per chart side_effect annotation; "
        f"got 0x{follow_up:08X}"
    )


