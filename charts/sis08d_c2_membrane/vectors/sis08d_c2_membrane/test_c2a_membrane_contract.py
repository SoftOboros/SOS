def test_c2a_manifest_references_all_emitted_artifacts():
    """The deterministic manifest must reference the chart, the SVD,
    both MPU tables (C + Rust), and every vector file under the
    chart's vector directory. Mismatch is a regression in the
    emitter, not the chart.
    """
    repo_root = Path(__file__).resolve().parents[4]
    manifest_path = (
        repo_root
        / "charts"
        / "sis08d_c2_membrane"
        / "sis08d_c2_membrane_manifest.json"
    )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    assert manifest["id"] == "sis08d-c2-membrane"
    # Path B per EOQ-002-ERRATA-002 (2026-05-28): placement amended from
    # "sram-membrane" to "mmio-peripheral" because the C2-A target
    # access mechanism is memory-mapped IO, not memory-backed SRAM.
    # The chart's semantic surface (shared region with command/status/
    # transfer channels) is unchanged; only the access-mechanism tag is.
    assert manifest["placement"] == "mmio-peripheral"
    assert manifest["descriptor"]["format"] == "cmsis-svd-1.3"
    assert manifest["descriptor"]["contentHash"].startswith("sha256:")
    assert manifest["chartHash"].startswith("sha256:")
    assert manifest["mpu"]["c"].endswith("sis08d_c2_membrane_mpu.c")
    assert manifest["mpu"]["rust"].endswith("sis08d_c2_membrane_mpu.rs")
    # Five channels per SIS-08D §4.
    assert len(manifest["channels"]) == 5
    names = {c["name"] for c in manifest["channels"]}
    assert names == {
        "membrane_command",
        "membrane_status",
        "transfer_mailbox_data",
        "transfer_mailbox_notify",
        "sram_window",
    }
