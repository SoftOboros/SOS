"""SIS-08D C2-A bespoke membrane-contract integration vector.

Hand-authored (not regenerated by ``tools/sos-codegen/vectors_emit.py``)
to satisfy ``docs/todo/streamz/statechart-orchestration/TODO-SIS-08D-C2-IMPLEMENTATION-PLAN.md``
§5 step 1 (interpreted-simulation evidence) and §4 (membrane-contract
requirements).

This vector exercises the **agreement** between the software side
and the SOS membrane descriptor on:

  * **Layout** — every channel's address derived from
    ``plans.json`` matches the SOS-09-B SVD address-offset policy.
  * **Ownership** — the SRAM window is SOS-owned (declared via the
    chart's ``sos:kind="shared"`` + ``sos:mutex="sram_window_lock"``
    annotations); the software side reads / writes through the bus
    facade only.
  * **Lifecycle** — command-write → status-publish round-trip on
    the SRAM-window membrane: software issues ``Start``, the
    hardware publishes ``Busy`` then ``Ready``, software reads the
    status, software issues ``Stop`` to return to ``Idle``.
  * **Transfer surface** — single-slot mailbox discipline: a single
    in-flight transfer posts to the data channel, the notify
    channel's ``non_empty`` strobes high, the software drains and
    the ``non_empty`` clears on read.
  * **Failure mode** — command-write while busy returns an
    ``Error`` status code (state=0x03) with a non-zero
    ``error_code`` byte; reading the status latch clears the
    error_code per the chart's ``side_effect="clear-on-read"``
    annotation.

The encoding constants here MUST stay in sync with the chart's
``sis08d_c2_membrane.scxml`` header comment (``Command encoding``
and ``Status encoding`` blocks). Drift between the two is the
exact failure mode this vector is meant to surface.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from vectors.harness import PythonCpuStubHarness

# ---------------------------------------------------------------------------
# Encoding constants — MUST mirror the SCXML chart header comment.
# ---------------------------------------------------------------------------

# Command field offsets (membrane_command, see chart bit_layout).
CMD_FIELD_LSB = 0
CMD_FIELD_MASK = 0xFF
SEQ_FIELD_LSB = 8
SEQ_FIELD_MASK = 0xFF00

# Status field offsets (membrane_status, see chart bit_layout).
STATE_FIELD_LSB = 0
STATE_FIELD_MASK = 0xFF
ERROR_CODE_LSB = 16
ERROR_CODE_MASK = 0x00FF0000
BUSY_BIT = 1 << 31

# Notify field offsets (transfer_mailbox_notify).
NOTIFY_NON_EMPTY_BIT = 1 << 0
NOTIFY_PRIORITY_LSB = 8
NOTIFY_PRIORITY_MASK = 0x0F00

# Command opcodes.
CMD_IDLE = 0x00
CMD_START = 0x01
CMD_STOP = 0x02
CMD_DRAIN = 0x03

# Status state codes.
STATE_IDLE = 0x00
STATE_BUSY = 0x01
STATE_READY = 0x02
STATE_ERROR = 0x03

# Error codes (synthetic — the spec just demands non-zero on busy-write).
ERR_BUSY_WRITE_REJECTED = 0x42


# ---------------------------------------------------------------------------
# Layout helpers — load plans.json (the SOS-09-B address-offset evidence).
# ---------------------------------------------------------------------------

_PLANS_JSON = Path(__file__).parent / "plans.json"


def _load_layout() -> dict[str, dict]:
    """Return ``{channel_name: plan}`` mapping from the emitted plans.json."""
    raw = json.loads(_PLANS_JSON.read_text(encoding="utf-8"))
    return {p["channel_name"]: p for p in raw["plans"]}


